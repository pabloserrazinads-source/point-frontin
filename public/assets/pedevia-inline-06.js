  const phone=normalizeCustomerPhoneV113(profile?.phone||getCachedCustomerPhoneV115()||window.checkoutState?.phone||'');
  const count=Math.max(0,Number(profile?.order_count||0));
  const required=Math.max(1,Number(offer?.requiredOrders||10));
  const percent=Math.max(0,Math.min(100,Number(offer?.rewardPercent||10)));
  const eligible=!!offer&&count>0&&(count%required===0)&&percent>0;
